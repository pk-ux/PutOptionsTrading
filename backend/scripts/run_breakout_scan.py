"""
Run the Breakout Scanner from the command line.
- Portions generated by AI

Runs a full scan using the universe + config stored in the database, persists
results, and publishes the top picks into the "Momentum Stocks" trade idea.

Usage (manual or via a scheduler):
    cd backend
    python -m scripts.run_breakout_scan

Schedule on Railway (cron service) or any host's crontab to refresh daily after
the close. See MIGRATION.md ("Breakout Scanner") for details.
"""

import os
import sys

# Add backend to path so `app...` imports resolve
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core.database import init_db
from app.modules.breakout_scanner.integration import run_and_publish


def main() -> int:
    print("Breakout Scanner: initializing database...")
    init_db()

    print("Breakout Scanner: starting scan...")
    summary = run_and_publish()

    status = summary.get("status")
    print(f"Breakout Scanner: {status} - {summary.get('message')}")

    result = summary.get("result") or {}
    candidates = result.get("candidates") or []
    if candidates:
        print("\nTop picks:")
        for c in candidates:
            print(
                f"  {c['rank']:>2}. {c['symbol']:<6} "
                f"score={c['score']:<6} setup={c.get('setup_type')} "
                f"iv_rank={c.get('iv_rank')} earnings_flag={c.get('earnings_flag')}"
            )

    return 0 if status == "success" else 1


if __name__ == "__main__":
    sys.exit(main())
