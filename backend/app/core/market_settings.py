"""
Market Settings Management
- Portions generated by AI

This module manages the in-memory state of market settings.
Settings are loaded from the database at startup and updated when changed via admin.
"""

from typing import Dict, Any


# Default settings (used if database not initialized)
DEFAULT_MARKET_SETTINGS = {
    "risk_free_rate": 0.0367,  # 3.67% from FRED DGS3MO as of Jan 2026
}

# In-memory storage for current market settings
_market_settings: Dict[str, Any] = DEFAULT_MARKET_SETTINGS.copy()


def load_market_settings_from_db():
    """
    Load market settings from database into memory.
    Called once at application startup.
    Creates default settings if none exist.
    """
    global _market_settings
    
    try:
        from ..core.database import SessionLocal
        from ..models import MarketSettings
        
        db = SessionLocal()
        try:
            settings = db.query(MarketSettings).filter(MarketSettings.id == 1).first()
            
            if settings:
                _market_settings = settings.to_dict()
                print(f"[Market Settings] Loaded from DB: risk_free_rate={settings.risk_free_rate:.4f} ({settings.risk_free_rate*100:.2f}%)")
            else:
                # Create default settings
                settings = MarketSettings(
                    id=1,
                    risk_free_rate=DEFAULT_MARKET_SETTINGS["risk_free_rate"],
                )
                db.add(settings)
                db.commit()
                _market_settings = settings.to_dict()
                print(f"[Market Settings] Created default in DB: risk_free_rate={settings.risk_free_rate:.4f}")
        finally:
            db.close()
    except Exception as e:
        print(f"[Market Settings] Error loading from DB: {e}")
        _market_settings = DEFAULT_MARKET_SETTINGS.copy()


def update_market_settings_in_memory(settings: Dict[str, Any]):
    """
    Update the in-memory market settings.
    Called when admin updates settings via the API.
    
    Args:
        settings: Dictionary with setting values
    """
    global _market_settings
    _market_settings = settings.copy()
    rate = settings.get('risk_free_rate', 0)
    print(f"[Market Settings] Updated in-memory: risk_free_rate={rate:.4f} ({rate*100:.2f}%)")


def get_market_settings() -> Dict[str, Any]:
    """Get the current market settings."""
    return _market_settings.copy()


def get_risk_free_rate() -> float:
    """
    Get the currently configured risk-free rate.
    Used by Greeks calculation functions.
    
    Returns:
        Risk-free rate as decimal (e.g., 0.0367 for 3.67%)
    """
    return _market_settings.get("risk_free_rate", DEFAULT_MARKET_SETTINGS["risk_free_rate"])
