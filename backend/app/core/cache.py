"""
Caching layer with Redis support and in-memory fallback
- Portions generated by AI

Provides caching for:
- Stock prices (configurable TTL, default 3 minutes)
- Options chains (configurable TTL, default 5 minutes)
- News (configurable TTL, default 15 minutes)

Cache settings are loaded from database at app startup and stored in memory.
"""

import json
import hashlib
from typing import Any, Optional, Dict
from datetime import datetime, timedelta

# Try to import redis, fall back to in-memory if not available
try:
    import redis
    REDIS_AVAILABLE = True
except ImportError:
    REDIS_AVAILABLE = False
    print("Redis not installed. Using in-memory cache (not suitable for production).")

from .config import get_settings


# Default TTL values (used until settings are loaded from database)
DEFAULT_CACHE_SETTINGS: Dict[str, Any] = {
    "cache_enabled": True,
    "ttl_stock_price": 180,      # 3 minutes
    "ttl_options_chain": 300,    # 5 minutes
    "ttl_news": 900,             # 15 minutes
    "ttl_event_dates": 604800,   # 1 week (earnings/dividend dates don't change often)
}

# In-memory cache settings (loaded from database at startup)
_cache_settings: Dict[str, Any] = DEFAULT_CACHE_SETTINGS.copy()


class InMemoryCache:
    """
    Simple in-memory cache for local development.
    NOT suitable for production with multiple workers.
    """
    
    def __init__(self):
        self._cache: dict[str, tuple[Any, datetime]] = {}
        print("Using in-memory cache (for local development only)")
    
    def get(self, key: str) -> Optional[str]:
        """Get value from cache if not expired"""
        if key in self._cache:
            value, expires_at = self._cache[key]
            if datetime.now() < expires_at:
                return value
            else:
                # Expired, remove it
                del self._cache[key]
        return None
    
    def set(self, key: str, value: str, ex: int = 300) -> None:
        """Set value with expiration (ex = seconds)"""
        self._evict_expired()
        expires_at = datetime.now() + timedelta(seconds=ex)
        self._cache[key] = (value, expires_at)
    
    def delete(self, key: str) -> None:
        """Delete a key from cache"""
        if key in self._cache:
            del self._cache[key]

    def delete_by_prefix(self, prefix: str) -> int:
        """Delete all keys that start with prefix. Returns count removed."""
        keys = [k for k in self._cache if k.startswith(prefix)]
        for key in keys:
            del self._cache[key]
        return len(keys)
    
    def flushall(self) -> None:
        """Clear all cached data"""
        self._cache.clear()
    
    def ping(self) -> bool:
        """Check if cache is available"""
        return True

    def _evict_expired(self) -> None:
        now = datetime.now()
        expired = [k for k, (_, expires_at) in self._cache.items() if now >= expires_at]
        for key in expired:
            del self._cache[key]


class RedisCache:
    """
    Redis cache wrapper for production use.
    Supports multiple workers and horizontal scaling.
    """
    
    def __init__(self, redis_url: str):
        self._client = redis.from_url(redis_url, decode_responses=True)
        # Test connection
        try:
            self._client.ping()
            print(f"Connected to Redis successfully")
        except redis.ConnectionError as e:
            raise ConnectionError(f"Could not connect to Redis: {e}")
    
    def get(self, key: str) -> Optional[str]:
        """Get value from Redis"""
        return self._client.get(key)
    
    def set(self, key: str, value: str, ex: int = 300) -> None:
        """Set value with expiration (ex = seconds)"""
        self._client.set(key, value, ex=ex)
    
    def delete(self, key: str) -> None:
        """Delete a key from cache"""
        self._client.delete(key)

    def delete_by_prefix(self, prefix: str) -> int:
        """Delete keys with this prefix. Avoids FLUSHALL on a shared Redis."""
        count = 0
        for key in self._client.scan_iter(match=f"{prefix}*"):
            self._client.delete(key)
            count += 1
        return count
    
    def flushall(self) -> None:
        """Clear all cached data (use with caution!)"""
        self._client.flushall()
    
    def ping(self) -> bool:
        """Check if Redis is available"""
        try:
            self._client.ping()
            return True
        except:
            return False


# Global cache instance
_cache_instance: Optional[InMemoryCache | RedisCache] = None


def get_cache() -> InMemoryCache | RedisCache:
    """
    Get or create the cache instance.
    Uses Redis if REDIS_URL is configured, otherwise falls back to in-memory.
    """
    global _cache_instance
    
    if _cache_instance is not None:
        return _cache_instance
    
    settings = get_settings()
    redis_url = getattr(settings, 'REDIS_URL', None)
    
    if redis_url and REDIS_AVAILABLE:
        try:
            _cache_instance = RedisCache(redis_url)
            return _cache_instance
        except ConnectionError as e:
            print(f"Redis connection failed, falling back to in-memory: {e}")
    
    # Fallback to in-memory cache
    _cache_instance = InMemoryCache()
    return _cache_instance


def make_cache_key(prefix: str, *args, **kwargs) -> str:
    """
    Generate a consistent cache key from prefix and arguments.
    
    Example:
        make_cache_key("options", "AAPL", max_dte=45, min_dte=15)
        -> "options:AAPL:hash_of_kwargs"
    """
    key_parts = [prefix] + [str(a) for a in args]
    
    if kwargs:
        # Sort kwargs for consistent ordering
        sorted_kwargs = sorted(kwargs.items())
        kwargs_str = json.dumps(sorted_kwargs)
        kwargs_hash = hashlib.md5(kwargs_str.encode()).hexdigest()[:8]
        key_parts.append(kwargs_hash)
    
    return ":".join(key_parts)


# ============== Cache Settings Management ==============

def load_cache_settings_from_db() -> Dict[str, Any]:
    """
    Load cache settings from database into memory.
    Called at app startup. Creates default settings if none exist.
    """
    global _cache_settings
    
    from .database import SessionLocal
    from ..models.cache_settings import CacheSettings
    
    try:
        db = SessionLocal()
        try:
            settings = db.query(CacheSettings).filter(CacheSettings.id == 1).first()
            
            if not settings:
                # Create default settings
                settings = CacheSettings(
                    id=1,
                    cache_enabled=True,
                    ttl_stock_price=180,
                    ttl_options_chain=300,
                    ttl_news=900,
                    ttl_event_dates=604800,  # 1 week for earnings/dividend dates
                )
                db.add(settings)
                db.commit()
                db.refresh(settings)
                print("Created default cache settings in database")
            
            _cache_settings = settings.to_dict()
            print(f"Loaded cache settings: enabled={_cache_settings['cache_enabled']}, "
                  f"ttl_stock={_cache_settings['ttl_stock_price']}s, "
                  f"ttl_options={_cache_settings['ttl_options_chain']}s, "
                  f"ttl_news={_cache_settings['ttl_news']}s")
            return _cache_settings
        finally:
            db.close()
    except Exception as e:
        print(f"Error loading cache settings from database: {e}")
        print("Using default cache settings")
        return _cache_settings


def update_cache_settings_in_memory(settings: Dict[str, Any]) -> None:
    """
    Update the in-memory cache settings.
    Called when admin updates settings via API.
    """
    global _cache_settings
    _cache_settings = {
        "cache_enabled": settings.get("cache_enabled", True),
        "ttl_stock_price": settings.get("ttl_stock_price", 180),
        "ttl_options_chain": settings.get("ttl_options_chain", 300),
        "ttl_news": settings.get("ttl_news", 900),
        "ttl_event_dates": settings.get("ttl_event_dates", 604800),
        "updated_at": settings.get("updated_at"),
    }
    print(f"Updated in-memory cache settings: enabled={_cache_settings['cache_enabled']}")


def get_cache_settings() -> Dict[str, Any]:
    """Get current cache settings from memory."""
    return _cache_settings.copy()


def is_cache_disabled() -> bool:
    """Check if caching is disabled (from in-memory settings)."""
    return not _cache_settings.get("cache_enabled", True)


def get_ttl_stock_price() -> int:
    """Get TTL for stock price cache."""
    return _cache_settings.get("ttl_stock_price", 180)


def get_ttl_options_chain() -> int:
    """Get TTL for options chain cache."""
    return _cache_settings.get("ttl_options_chain", 300)


def get_ttl_news() -> int:
    """Get TTL for news cache."""
    return _cache_settings.get("ttl_news", 900)


def get_ttl_event_dates() -> int:
    """Get TTL for event dates (earnings/dividend) cache."""
    return _cache_settings.get("ttl_event_dates", 604800)


# Convenience functions for common cache operations

def cache_get_json(key: str) -> Optional[Any]:
    """Get JSON value from cache"""
    if is_cache_disabled():
        return None
    cache = get_cache()
    value = cache.get(key)
    if value:
        try:
            return json.loads(value)
        except json.JSONDecodeError:
            return None
    return None


def cache_set_json(key: str, value: Any, ttl: int = 300) -> None:
    """Set JSON value in cache with TTL"""
    if is_cache_disabled():
        return
    cache = get_cache()
    cache.set(key, json.dumps(value), ex=ttl)


def clear_app_cache() -> int:
    """
    Drop this app's market-data keys only (price/options/news/events/indicators).
    Does not FLUSHALL, so a shared Redis is left intact.
    """
    cache = get_cache()
    deleted = 0
    for prefix in ("price:", "options:", "news:", "events:", "indicators:", "candles:"):
        deleted += cache.delete_by_prefix(prefix)
    return deleted


def _normalize_symbol(symbol: str) -> str:
    return (symbol or "").upper().strip()


def _price_key(symbol: str, provider: str, use_midpoint: bool) -> str:
    return make_cache_key("price", _normalize_symbol(symbol), provider, int(bool(use_midpoint)))


def _options_key(symbol: str, provider: str, min_dte: int, max_dte: int, use_midpoint: bool) -> str:
    # Raw chains are fetched by DTE window + provider pricing, then filtered in-process.
    return make_cache_key(
        "options",
        _normalize_symbol(symbol),
        provider,
        int(min_dte),
        int(max_dte),
        int(bool(use_midpoint)),
    )


def _news_key(symbol: str, provider: str, max_age_days: int, limit: int) -> str:
    return make_cache_key("news", _normalize_symbol(symbol), provider, int(max_age_days), int(limit))


def get_cached_stock_price(symbol: str, provider: str, use_midpoint: bool = False) -> Optional[Any]:
    """
    Get cached stock price data.
    
    Returns:
        Either a dict with {price, previous_close, change_percent} (new format)
        or a float (legacy format for backward compatibility)
    """
    return cache_get_json(_price_key(symbol, provider, use_midpoint))


def set_cached_stock_price(symbol: str, price_data: Any, provider: str, use_midpoint: bool = False) -> None:
    """
    Cache stock price data with configured TTL.
    
    Args:
        symbol: Stock ticker symbol
        price_data: Either a dict with {price, previous_close, change_percent}
                   or a float (legacy format for backward compatibility)
        provider: Active market-data provider
        use_midpoint: Alpaca mid-point pricing flag
    """
    cache_set_json(_price_key(symbol, provider, use_midpoint), price_data, ttl=get_ttl_stock_price())


def get_cached_options_chain(
    symbol: str,
    provider: str,
    min_dte: int,
    max_dte: int,
    use_midpoint: bool = False,
) -> Optional[list]:
    """Get cached raw options chain for this DTE window and provider."""
    return cache_get_json(_options_key(symbol, provider, min_dte, max_dte, use_midpoint))


def set_cached_options_chain(
    symbol: str,
    options: list,
    provider: str,
    min_dte: int,
    max_dte: int,
    use_midpoint: bool = False,
) -> None:
    """Cache raw options chain with configured TTL"""
    cache_set_json(
        _options_key(symbol, provider, min_dte, max_dte, use_midpoint),
        options,
        ttl=get_ttl_options_chain(),
    )


def get_cached_news(symbol: str, provider: str, max_age_days: int = 7, limit: int = 10) -> Optional[list]:
    """Get cached news"""
    return cache_get_json(_news_key(symbol, provider, max_age_days, limit))


def set_cached_news(symbol: str, news: list, provider: str, max_age_days: int = 7, limit: int = 10) -> None:
    """Cache news with configured TTL"""
    cache_set_json(_news_key(symbol, provider, max_age_days, limit), news, ttl=get_ttl_news())


def get_cached_event_dates(symbol: str) -> Optional[Dict]:
    """Get cached event dates (earnings/dividend) for a symbol"""
    key = make_cache_key("events", _normalize_symbol(symbol))
    return cache_get_json(key)


def set_cached_event_dates(symbol: str, data: Dict) -> None:
    """Cache event dates with configured TTL (default 1 week)"""
    key = make_cache_key("events", _normalize_symbol(symbol))
    cache_set_json(key, data, ttl=get_ttl_event_dates())


def get_cached_indicators(symbol: str, session: Optional[str] = None) -> Optional[Dict]:
    """Get cached daily SMA/RSI for this symbol and market session."""
    if session is None:
        from .market_clock import market_today
        session = market_today().isoformat()
    key = make_cache_key("indicators", _normalize_symbol(symbol), session)
    return cache_get_json(key)


def set_cached_indicators(symbol: str, data: Dict, session: Optional[str] = None) -> None:
    """Cache daily SMA/RSI for the rest of the session (date is part of the key)."""
    if session is None:
        from .market_clock import market_today
        session = market_today().isoformat()
    key = make_cache_key("indicators", _normalize_symbol(symbol), session)
    cache_set_json(key, data, ttl=12 * 3600)


# Daily candles only change via today's partial bar; 30 min keeps them fresh
# intraday while bounding yfinance calls.
CANDLES_TTL_SECONDS = 1800


def get_cached_candles(symbol: str) -> Optional[Dict]:
    """Get cached daily candles + indicator overlays for the price chart."""
    return cache_get_json(make_cache_key("candles", _normalize_symbol(symbol)))


def set_cached_candles(symbol: str, data: Dict) -> None:
    """Cache daily candles + indicator overlays."""
    cache_set_json(make_cache_key("candles", _normalize_symbol(symbol)), data, ttl=CANDLES_TTL_SECONDS)


def get_config_hash(config: dict) -> str:
    """Generate a hash for the config to use in cache keys"""
    config_str = json.dumps(config, sort_keys=True)
    return hashlib.md5(config_str.encode()).hexdigest()[:8]
