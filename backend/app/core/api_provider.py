"""
API Provider Settings Management
- Portions generated by AI

This module manages the in-memory state of API provider settings.
Settings are loaded from the database at startup and updated when changed via admin.
"""

from typing import Dict, Any, Optional


# Default settings (used if database not initialized)
DEFAULT_API_PROVIDER_SETTINGS = {
    "active_provider": "massive",  # "massive" or "alpaca"
    "use_midpoint_pricing": True,
}

# In-memory storage for current provider settings
_api_provider_settings: Dict[str, Any] = DEFAULT_API_PROVIDER_SETTINGS.copy()


def load_api_provider_settings_from_db():
    """
    Load API provider settings from database into memory.
    Called once at application startup.
    Creates default settings if none exist.
    """
    global _api_provider_settings
    
    try:
        from ..core.database import SessionLocal
        from ..models import ApiProviderSettings
        
        db = SessionLocal()
        try:
            settings = db.query(ApiProviderSettings).filter(ApiProviderSettings.id == 1).first()
            
            if settings:
                _api_provider_settings = settings.to_dict()
                print(f"[API Provider] Loaded settings from DB: provider={settings.active_provider}")
            else:
                # Create default settings
                settings = ApiProviderSettings(
                    id=1,
                    active_provider=DEFAULT_API_PROVIDER_SETTINGS["active_provider"],
                    use_midpoint_pricing=DEFAULT_API_PROVIDER_SETTINGS["use_midpoint_pricing"],
                )
                db.add(settings)
                db.commit()
                _api_provider_settings = settings.to_dict()
                print("[API Provider] Created default settings in DB")
        finally:
            db.close()
    except Exception as e:
        print(f"[API Provider] Error loading settings from DB: {e}")
        _api_provider_settings = DEFAULT_API_PROVIDER_SETTINGS.copy()


def update_api_provider_settings_in_memory(settings: Dict[str, Any]):
    """
    Update the in-memory API provider settings.
    Called when admin updates settings via the API.
    
    Args:
        settings: Dictionary with setting values
    """
    global _api_provider_settings
    _api_provider_settings = settings.copy()
    print(f"[API Provider] Updated in-memory settings: provider={settings.get('active_provider')}")
    
    # Reset the Alpaca client singleton when settings change
    from ..services.alpaca_api_client import reset_alpaca_client
    reset_alpaca_client()


def get_api_provider_settings() -> Dict[str, Any]:
    """Get the current API provider settings."""
    return _api_provider_settings.copy()


def get_active_provider() -> str:
    """Get the currently active API provider name."""
    return _api_provider_settings.get("active_provider", "massive")


def get_use_midpoint_pricing() -> bool:
    """Get whether to use mid-point pricing for Alpaca."""
    return _api_provider_settings.get("use_midpoint_pricing", True)


def is_alpaca_active() -> bool:
    """Check if Alpaca is the active provider."""
    return get_active_provider() == "alpaca"


def is_massive_active() -> bool:
    """Check if Massive is the active provider."""
    return get_active_provider() == "massive"
