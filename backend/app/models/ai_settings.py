"""
AISettings database model for storing AI analysis configuration
- Portions generated by AI
"""

from datetime import datetime
from sqlalchemy import Column, Integer, Boolean, String, DateTime

from ..core.database import Base


class AISettings(Base):
    """
    Singleton-style model for AI analysis configuration.
    Only one row with id=1 should exist.
    """
    __tablename__ = "ai_settings"
    
    id = Column(Integer, primary_key=True, default=1)
    ai_enabled = Column(Boolean, default=True, nullable=False)
    active_provider = Column(String(50), default="gemini", nullable=False)  # gemini, groq, openai
    cache_enabled = Column(Boolean, default=True, nullable=False)
    cache_ttl_seconds = Column(Integer, default=86400, nullable=False)  # 1 day default
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    
    def __repr__(self):
        return f"<AISettings enabled={self.ai_enabled} provider={self.active_provider}>"
    
    def to_dict(self) -> dict:
        """Convert to dictionary"""
        return {
            "ai_enabled": self.ai_enabled,
            "active_provider": self.active_provider,
            "cache_enabled": self.cache_enabled,
            "cache_ttl_seconds": self.cache_ttl_seconds,
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }
