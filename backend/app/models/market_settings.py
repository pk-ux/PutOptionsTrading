"""
MarketSettings database model for storing market-related configuration
- Portions generated by AI
"""

from datetime import datetime
from sqlalchemy import Column, Integer, Float, DateTime

from ..core.database import Base
from ..core.market_clock import to_market_iso


class MarketSettings(Base):
    """
    Singleton-style model for market-related settings.
    Only one row with id=1 should exist.
    
    Attributes:
        risk_free_rate: The risk-free interest rate for Greeks calculations (as decimal, e.g., 0.0367 for 3.67%)
    """
    __tablename__ = "market_settings"
    
    id = Column(Integer, primary_key=True, default=1)
    risk_free_rate = Column(Float, default=0.0367, nullable=False)  # Current: 3.67% (from FRED DGS3MO)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    
    def __repr__(self):
        return f"<MarketSettings risk_free_rate={self.risk_free_rate}>"
    
    def to_dict(self) -> dict:
        """Convert to dictionary"""
        return {
            "risk_free_rate": self.risk_free_rate,
            "updated_at": to_market_iso(self.updated_at),
        }
