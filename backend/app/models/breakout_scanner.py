"""
Breakout Scanner database models.
- Portions generated by AI

- BreakoutScannerSettings: singleton (id=1) holding the scan universe + config
  + last-run status (follows the AISettings/CacheSettings pattern).
- BreakoutScanResult: one row per ranked candidate from the latest runs, powering
  the Admin results table and CSP context.
"""

import json
import uuid
from datetime import datetime
from typing import Any, Dict, List

from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    Index,
    Integer,
    String,
    Text,
)

from ..core.database import Base


class BreakoutScannerSettings(Base):
    """Singleton-style configuration for the breakout scanner (id=1)."""

    __tablename__ = "breakout_scanner_settings"

    id = Column(Integer, primary_key=True, default=1)
    enabled = Column(Boolean, default=True, nullable=False)

    # The user-managed scan universe (comma-separated tickers)
    universe = Column(Text, default="", nullable=False)

    # Scoring config
    top_n = Column(Integer, default=15, nullable=False)
    deep_dive_n = Column(Integer, default=40, nullable=False)
    use_unusual_whales = Column(Boolean, default=True, nullable=False)
    weights = Column(Text, nullable=True)  # JSON string; null -> module defaults

    # Stage-1 pre-filter
    min_price = Column(Float, default=10.0, nullable=False)
    max_price = Column(Float, default=600.0, nullable=False)
    min_avg_volume = Column(Integer, default=500000, nullable=False)
    require_above_sma200 = Column(Boolean, default=False, nullable=False)
    typical_csp_dte = Column(Integer, default=35, nullable=False)

    # Run status
    last_run_at = Column(DateTime, nullable=True)
    last_run_status = Column(String(20), default="idle", nullable=False)  # idle|running|success|error
    last_run_message = Column(Text, nullable=True)
    last_market_context = Column(Text, nullable=True)  # JSON snapshot of regime/fear-greed

    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    def get_universe_list(self) -> List[str]:
        if not self.universe:
            return []
        return [s.strip().upper() for s in self.universe.split(",") if s.strip()]

    def get_weights(self) -> Dict[str, float]:
        if not self.weights:
            return {}
        try:
            return json.loads(self.weights)
        except (ValueError, TypeError):
            return {}

    def get_market_context(self) -> Dict[str, Any]:
        if not self.last_market_context:
            return {}
        try:
            return json.loads(self.last_market_context)
        except (ValueError, TypeError):
            return {}

    def to_dict(self) -> Dict[str, Any]:
        return {
            "enabled": self.enabled,
            "universe": self.get_universe_list(),
            "top_n": self.top_n,
            "deep_dive_n": self.deep_dive_n,
            "use_unusual_whales": self.use_unusual_whales,
            "weights": self.get_weights(),
            "min_price": self.min_price,
            "max_price": self.max_price,
            "min_avg_volume": self.min_avg_volume,
            "require_above_sma200": self.require_above_sma200,
            "typical_csp_dte": self.typical_csp_dte,
            "last_run_at": self.last_run_at.isoformat() if self.last_run_at else None,
            "last_run_status": self.last_run_status,
            "last_run_message": self.last_run_message,
            "market_context": self.get_market_context(),
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }


class BreakoutScanResult(Base):
    """A single ranked candidate from a scan run."""

    __tablename__ = "breakout_scan_results"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    run_at = Column(DateTime, default=datetime.utcnow, nullable=False, index=True)

    symbol = Column(String(16), nullable=False)
    score = Column(Float, default=0.0, nullable=False)
    rank = Column(Integer, default=0, nullable=False)
    setup_type = Column(String(40), nullable=True)
    pivot_price = Column(Float, nullable=True)
    current_price = Column(Float, nullable=True)

    breakout_trigger = Column(Boolean, default=False, nullable=False)
    volume_expansion = Column(Float, nullable=True)
    pct_from_52wk_high = Column(Float, nullable=True)

    iv_rank = Column(Float, nullable=True)
    implied_move = Column(Float, nullable=True)
    iv_vs_realized = Column(Float, nullable=True)
    net_call_premium = Column(Float, nullable=True)
    bullish_flow_score = Column(Float, nullable=True)
    gex_regime = Column(String(20), nullable=True)
    gamma_wall = Column(Float, nullable=True)
    max_pain = Column(Float, nullable=True)
    dark_pool_accum = Column(Boolean, default=False, nullable=False)
    smart_money = Column(Boolean, default=False, nullable=False)
    next_earnings_date = Column(String(20), nullable=True)
    earnings_flag = Column(Boolean, default=False, nullable=False)
    suggested_put_strike = Column(Float, nullable=True)
    factor_breakdown = Column(Text, nullable=True)  # JSON string

    __table_args__ = (
        Index("idx_breakout_results_run", "run_at", "rank"),
    )

    def to_dict(self) -> Dict[str, Any]:
        breakdown = {}
        if self.factor_breakdown:
            try:
                breakdown = json.loads(self.factor_breakdown)
            except (ValueError, TypeError):
                breakdown = {}
        return {
            "symbol": self.symbol,
            "score": self.score,
            "rank": self.rank,
            "setup_type": self.setup_type,
            "pivot_price": self.pivot_price,
            "current_price": self.current_price,
            "breakout_trigger": self.breakout_trigger,
            "volume_expansion": self.volume_expansion,
            "pct_from_52wk_high": self.pct_from_52wk_high,
            "iv_rank": self.iv_rank,
            "implied_move": self.implied_move,
            "iv_vs_realized": self.iv_vs_realized,
            "net_call_premium": self.net_call_premium,
            "bullish_flow_score": self.bullish_flow_score,
            "gex_regime": self.gex_regime,
            "gamma_wall": self.gamma_wall,
            "max_pain": self.max_pain,
            "dark_pool_accum": self.dark_pool_accum,
            "smart_money": self.smart_money,
            "next_earnings_date": self.next_earnings_date,
            "earnings_flag": self.earnings_flag,
            "suggested_put_strike": self.suggested_put_strike,
            "factor_breakdown": breakdown,
            "run_at": self.run_at.isoformat() if self.run_at else None,
        }
