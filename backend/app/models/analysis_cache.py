"""
Analysis Cache model for persistent storage of AI analysis results
- Portions generated by AI
"""

from datetime import datetime
from sqlalchemy import Column, Integer, String, Text, DateTime, Index

from ..core.database import Base


class AnalysisCache(Base):
    """Persistent cache for AI stock analysis results."""
    
    __tablename__ = "analysis_cache"
    
    id = Column(Integer, primary_key=True, index=True)
    symbol = Column(String(10), nullable=False, index=True, unique=True)
    analysis_json = Column(Text, nullable=False)  # JSON string of analysis result
    created_at = Column(DateTime, default=datetime.utcnow)
    expires_at = Column(DateTime, nullable=False, index=True)
    
    # Index for efficient lookups
    __table_args__ = (
        Index('ix_analysis_cache_symbol_expires', 'symbol', 'expires_at'),
    )
