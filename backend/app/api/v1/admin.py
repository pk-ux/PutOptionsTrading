@router.put("/market-settings", response_model=MarketSettingsResponse)
async def update_market_settings(
    data: MarketSettingsUpdate,
    admin: User = Depends(get_current_admin),
    db: Session = Depends(get_db)
):
    """
    Update market settings (admin only).
    
    The risk-free rate should be provided as a decimal (e.g., 0.0367 for 3.67%).
    Get the current rate from: https://fred.stlouisfed.org/series/DGS3MO
    """
    from ...core.market_settings import update_market_settings_in_memory
    
    settings = _get_or_create_market_settings(db)
    
    # Validate risk-free rate if provided
    if data.risk_free_rate is not None:
        if data.risk_free_rate < 0 or data.risk_free_rate > 1:
            raise HTTPException(
                status_code=400,
                detail="Risk-free rate must be between 0 and 1 (e.g., 0.0367 for 3.67%)"
            )
        settings.risk_free_rate = data.risk_free_rate
    
    db.commit()
    db.refresh(settings)
    
    # Update in-memory market settings
    update_market_settings_in_memory(settings.to_dict())
    
    return MarketSettingsResponse(
        risk_free_rate=settings.risk_free_rate,
        risk_free_rate_percent=settings.risk_free_rate * 100,
        updated_at=to_market_iso(settings.updated_at),
    )


