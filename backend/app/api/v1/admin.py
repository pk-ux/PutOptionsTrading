class ApiProviderSettingsResponse(BaseModel):
    """Response schema for API provider settings"""
    active_provider: str  # "massive" or "alpaca"
    use_midpoint_pricing: bool
    massive_api_configured: bool
    alpaca_api_configured: bool
    updated_at: str | None = None


class ApiProviderSettingsUpdate(BaseModel):
    """Request schema for updating API provider settings"""
    active_provider: Literal["massive", "alpaca"] | None = None
    use_midpoint_pricing: bool | None = None


def _get_or_create_api_provider_settings(db: Session) -> ApiProviderSettings:
    """Get the API provider settings row, creating it with defaults if it doesn't exist."""
    settings = db.query(ApiProviderSettings).filter(ApiProviderSettings.id == 1).first()
    if not settings:
        settings = ApiProviderSettings(
            id=1,
            active_provider="massive",
            use_midpoint_pricing=True,
        )
        db.add(settings)
        db.commit()
        db.refresh(settings)
    return settings


def _check_api_keys_configured() -> tuple[bool, bool]:
    """Check if API keys are configured for each provider."""
    settings = get_settings()
    massive_configured = bool(settings.MASSIVE_API_KEY)
    alpaca_configured = bool(settings.ALPACA_API_KEY and settings.ALPACA_SECRET_KEY)
    return massive_configured, alpaca_configured


@router.get("/api-provider", response_model=ApiProviderSettingsResponse)
async def get_api_provider_settings(
    admin: User = Depends(get_current_admin),
    db: Session = Depends(get_db)
):
    """Get current API provider settings (admin only)."""
    settings = _get_or_create_api_provider_settings(db)
    massive_configured, alpaca_configured = _check_api_keys_configured()
    
    return ApiProviderSettingsResponse(
        active_provider=settings.active_provider,
        use_midpoint_pricing=settings.use_midpoint_pricing,
        massive_api_configured=massive_configured,
        alpaca_api_configured=alpaca_configured,
        updated_at=to_market_iso(settings.updated_at),
    )


@router.put("/api-provider", response_model=ApiProviderSettingsResponse)
async def update_api_provider_settings(
    data: ApiProviderSettingsUpdate,
    admin: User = Depends(get_current_admin),
    db: Session = Depends(get_db)
):
    """Update API provider settings (admin only)."""
    from ...core.api_provider import update_api_provider_settings_in_memory
    
    settings = _get_or_create_api_provider_settings(db)
    massive_configured, alpaca_configured = _check_api_keys_configured()
    
    # Validate provider switch
    if data.active_provider:
        if data.active_provider == "alpaca" and not alpaca_configured:
            raise HTTPException(
                status_code=400,
                detail="Cannot switch to Alpaca: ALPACA_API_KEY and ALPACA_SECRET_KEY are not configured"
            )
        if data.active_provider == "massive" and not massive_configured:
            raise HTTPException(
                status_code=400,
                detail="Cannot switch to Massive: MASSIVE_API_KEY is not configured"
            )
    
    # Update fields that were provided
    update_data = data.model_dump(exclude_unset=True)
    for field, value in update_data.items():
        setattr(settings, field, value)
    
    db.commit()
    db.refresh(settings)
    
    # Update in-memory API provider settings
    update_api_provider_settings_in_memory(settings.to_dict())
    
    return ApiProviderSettingsResponse(
        active_provider=settings.active_provider,
        use_midpoint_pricing=settings.use_midpoint_pricing,
        massive_api_configured=massive_configured,
        alpaca_api_configured=alpaca_configured,
        updated_at=to_market_iso(settings.updated_at),
    )


