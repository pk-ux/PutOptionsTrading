def _put_seller_note(
    direction: str,
    stability: Optional[str],
    strike: Optional[float],
    levels: Dict[str, Optional[float]],
) -> str:
    """One sentence translating the read into cash-secured-put terms."""
    vwap = levels.get("dark_pool_vwap")
    max_pain = levels.get("max_pain")

    if strike is None:
        base = {
            "BULLISH": "Positioning leans higher, which favors selling puts here.",
            "BEARISH": "Positioning leans lower — assignment risk is elevated.",
        }.get(direction, "Positioning is mixed; no directional edge either way.")
        if stability == "amplifying":
            base += " Dealers are short gamma, so moves can overshoot."
        return base

    parts: List[str] = []
    if vwap:
        side = "below" if strike < vwap else "above"
        parts.append(f"your ${strike:,.2f} strike sits {side} the ${vwap:,.2f} dark-pool average")
    if max_pain:
        parts.append(f"max pain is ${max_pain:,.2f}")

    verdict = {
        "BULLISH": "flow is supportive for selling this put",
        "BEARISH": "flow argues for caution on assignment risk",
    }.get(direction, "flow is neutral for this strike")

    note = f"{' and '.join(parts).capitalize()}, so {verdict}." if parts else f"{verdict.capitalize()}."
    if stability == "amplifying":
        note += " Dealers are short gamma, so expect larger swings."
    return note


def score_direction(
    bundle: Dict[str, Any],
    spot: Optional[float],
    expiry: Optional[str] = None,
    strike: Optional[float] = None,
) -> Dict[str, Any]:
    """Combine the raw UW bundle into a directional read. Pure, no I/O."""
    dte_target = _dte(expiry) if expiry else None

    raw: Dict[str, Tuple[float, str]] = {}
    stability: Optional[str] = None
    gamma_regime: Optional[str] = None
    dp_vwap: Optional[float] = None
    dp_poc: Optional[float] = None
    max_pain_level: Optional[float] = None

    flow = _signal_flow(bundle.get("flow_per_expiry"), dte_target)
    if flow:
        raw["flow_sentiment"] = flow

    delta = _signal_delta_trend(bundle.get("greek_series"))
    if delta:
        raw["delta_trend"] = delta

    gamma = _signal_gamma(bundle.get("greek_series"))
    if gamma:
        raw["gamma_regime"] = (gamma[0], gamma[1])
        gamma_regime = gamma[2]
        stability = "stabilizing" if gamma[0] > 0 else "amplifying"

    dark = _signal_dark_pool(bundle.get("dark_pool_levels"), spot)
    if dark:
        raw["dark_pool"] = (dark[0], dark[1])
        dp_vwap, dp_poc = dark[2], dark[3]

    insider = _signal_insider(bundle.get("insider_flow"))
    if insider:
        raw["insider"] = insider

    pain = _signal_max_pain(bundle.get("max_pain"), spot, expiry)
    if pain:
        raw["max_pain"] = (pain[0], pain[1])
        max_pain_level = pain[2]

    weight_total = sum(DIRECTION_WEIGHTS[k] for k in raw)
    score = (
        sum(DIRECTION_WEIGHTS[k] * s for k, (s, _) in raw.items()) / weight_total
        if weight_total > 0
        else 0.0
    )
    coverage = weight_total / sum(DIRECTION_WEIGHTS.values())

    if score >= DIRECTION_THRESHOLD:
        direction = "BULLISH"
    elif score <= -DIRECTION_THRESHOLD:
        direction = "BEARISH"
    else:
        direction = "NEUTRAL"

    # Confidence falls for missing data, disagreement, or a score near zero —
    # three genuinely different reasons to distrust the read.
    if weight_total > 0:
        agreeing = 0.0
        for key, (s, _) in raw.items():
            w = DIRECTION_WEIGHTS[key]
            if abs(s) < 0.05:
                agreeing += w * 0.5
            elif (s > 0) == (score > 0):
                agreeing += w
        agreement = agreeing / weight_total
    else:
        agreement = 0.0
    magnitude = min(1.0, abs(score) / 0.5)
    confidence = coverage * (0.40 + 0.60 * agreement) * (0.45 + 0.55 * magnitude)

    signals = [
        {
            "key": key,
            "label": SIGNAL_LABELS[key],
            "weight": DIRECTION_WEIGHTS[key],
            "score": round(raw[key][0], 3) if key in raw else None,
            "detail": raw[key][1] if key in raw else "No data available",
            "available": key in raw,
        }
        for key in DIRECTION_WEIGHTS
    ]

    levels: Dict[str, Optional[float]] = {
        "dark_pool_vwap": round(dp_vwap, 2) if dp_vwap else None,
        "point_of_control": round(dp_poc, 2) if dp_poc else None,
        "max_pain": round(max_pain_level, 2) if max_pain_level else None,
    }

    return {
        "symbol": bundle.get("symbol", ""),
        "as_of": to_market_iso(datetime.now(timezone.utc)),
        "direction": direction,
        "score": round(score * 100.0, 1),
        "confidence": round(confidence, 3),
        "coverage": round(coverage, 3),
        "stability": stability,
        "gamma_regime": gamma_regime,
        "signals": signals,
        "levels": levels,
        "put_seller_note": _put_seller_note(direction, stability, strike, levels),
        "disclaimer": DISCLAIMER,
    }
