    def _format_price_data(self, yahoo_data: Dict[str, Any]) -> str:
        """Format Yahoo Finance price data for prompt."""
        if not yahoo_data:
            return "Data unavailable"
        
        lines = []
        if 'current_price' in yahoo_data:
            lines.append(f"Current Price: ${yahoo_data['current_price']:.2f}")
        if 'previous_close' in yahoo_data:
            lines.append(f"Previous Close: ${yahoo_data['previous_close']:.2f}")
        if 'change_percent' in yahoo_data:
            lines.append(f"Change: {yahoo_data['change_percent']:+.2f}%")
        if 'fifty_two_week_high' in yahoo_data:
            lines.append(f"52-Week High: ${yahoo_data['fifty_two_week_high']:.2f}")
        if 'fifty_two_week_low' in yahoo_data:
            lines.append(f"52-Week Low: ${yahoo_data['fifty_two_week_low']:.2f}")
        if 'volume' in yahoo_data:
            lines.append(f"Volume: {yahoo_data['volume']:,}")
        if 'avg_volume' in yahoo_data:
            lines.append(f"Avg Volume: {yahoo_data['avg_volume']:,}")
        if 'market_cap' in yahoo_data:
            lines.append(f"Market Cap: ${yahoo_data['market_cap']:,.0f}")
        if 'pe_ratio' in yahoo_data and yahoo_data['pe_ratio']:
            lines.append(f"P/E Ratio: {yahoo_data['pe_ratio']:.2f}")
        if 'beta' in yahoo_data and yahoo_data['beta']:
            lines.append(f"Beta: {yahoo_data['beta']:.2f}")
        
        return "\n".join(lines) if lines else "Data unavailable"
    
    def _format_technicals(self, technicals: Dict[str, Any]) -> str:
        """Format technical indicators for prompt."""
        if not technicals:
            return "Data unavailable"
        
        lines = []
        if technicals.get('rsi_14') is not None:
            lines.append(f"RSI(14): {technicals['rsi_14']:.1f}")
        if technicals.get('sma_20') is not None:
            lines.append(f"SMA(20): ${technicals['sma_20']:.2f}")
        if technicals.get('sma_50') is not None:
            lines.append(f"SMA(50): ${technicals['sma_50']:.2f}")
        if technicals.get('sma_200') is not None:
            lines.append(f"SMA(200): ${technicals['sma_200']:.2f}")
        if technicals.get('trend'):
            lines.append(f"Trend: {technicals['trend']}")
        if technicals.get('support_level') is not None:
            lines.append(f"Support: ${technicals['support_level']:.2f}")
        if technicals.get('resistance_level') is not None:
            lines.append(f"Resistance: ${technicals['resistance_level']:.2f}")
        
        return "\n".join(lines) if lines else "Data unavailable"
    
    def _format_news(self, news: list) -> str:
        """Format news items for prompt."""
        if not news:
            return "No recent news available"
        
        lines = []
        for item in news[:10]:  # Limit to 10 items
            title = item.get('title', 'Unknown')
            date = item.get('date_display', '')
            source = item.get('source', '')
            source_str = f" ({source})" if source else ""
            date_str = f" [{date}]" if date else ""
            lines.append(f"- {title}{source_str}{date_str}")
        
        return "\n".join(lines)
    
    def _format_analyst_ratings(self, ratings: Optional[Dict[str, Any]]) -> str:
        """Format analyst ratings for prompt."""
        if not ratings:
            return "Data unavailable"
        
        lines = []
        if ratings.get('rating'):
            lines.append(f"Consensus Rating: {ratings['rating']}")
        if ratings.get('target_price'):
            lines.append(f"Average Price Target: ${ratings['target_price']:.2f}")
        
        buy = ratings.get('buy_count', 0)
        hold = ratings.get('hold_count', 0)
        sell = ratings.get('sell_count', 0)
        if buy or hold or sell:
            lines.append(f"Analyst Distribution: Buy={buy}, Hold={hold}, Sell={sell}")
        
        return "\n".join(lines) if lines else "Data unavailable"
    
    def _format_short_interest(self, short_data: Optional[Dict[str, Any]]) -> str:
        """Format short interest data for prompt."""
        if not short_data:
            return "Data unavailable"
        
        lines = []
        if short_data.get('short_interest'):
            lines.append(f"Short Volume: {short_data['short_interest']:,}")
        if short_data.get('short_interest_percent'):
            lines.append(f"Short Interest %: {short_data['short_interest_percent']:.2f}%")
        if short_data.get('date'):
            lines.append(f"As of: {short_data['date']}")
        
        return "\n".join(lines) if lines else "Data unavailable"
    
    def _format_events(self, data: Dict[str, Any]) -> str:
        """Format upcoming events for prompt."""
        lines = []
        
        yahoo = data.get('yahoo', {})
        if yahoo.get('earnings_date'):
            days = yahoo.get('days_to_earnings')
            days_str = f" ({days} days away)" if days is not None else ""
            lines.append(f"Earnings: {yahoo['earnings_date']}{days_str}")
        
        if yahoo.get('ex_dividend_date'):
            lines.append(f"Ex-Dividend: {yahoo['ex_dividend_date']}")
        
        return "\n".join(lines) if lines else "No upcoming events found"
