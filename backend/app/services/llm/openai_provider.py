"""
OpenAI LLM Provider for AI stock analysis
- Portions generated by AI

Uses GPT-4o-mini (~$0.001 per analysis)
"""

import time
from typing import Dict, Any
from openai import OpenAI

from .base import BaseLLMProvider, AnalysisError
from ...core.config import get_settings


class OpenAIProvider(BaseLLMProvider):
    """OpenAI provider for stock analysis using GPT-4o-mini."""
    
    name = "openai"
    
    def __init__(self):
        self.settings = get_settings()
        self._client = None
        
        if self.is_available():
            self._client = OpenAI(api_key=self.settings.OPENAI_API_KEY)
    
    def is_available(self) -> bool:
        """Check if OpenAI is configured."""
        return bool(self.settings.OPENAI_API_KEY)
    
    async def generate_analysis(self, prompt: str) -> Dict[str, Any]:
        """Generate analysis using OpenAI."""
        if not self.is_available():
            raise AnalysisError("OpenAI API key not configured")
        
        try:
            start_time = time.time()
            
            response = self._client.chat.completions.create(
                model="gpt-4o-mini",
                messages=[
                    {"role": "system", "content": self.get_system_prompt()},
                    {"role": "user", "content": prompt}
                ],
                temperature=0.3,
                max_tokens=4096,
                response_format={"type": "json_object"},  # OpenAI native JSON mode
            )
            
            elapsed = time.time() - start_time
            print(f"[OpenAI] Response time: {elapsed:.2f}s")
            
            if not response.choices or not response.choices[0].message.content:
                raise AnalysisError("Empty response from OpenAI")
            
            return self.extract_json_from_response(response.choices[0].message.content)
            
        except AnalysisError:
            raise
        except Exception as e:
            if "API key" in str(e).lower() or "authentication" in str(e).lower():
                raise AnalysisError("Invalid OpenAI API key")
            raise AnalysisError(f"OpenAI analysis failed: {str(e)}")
