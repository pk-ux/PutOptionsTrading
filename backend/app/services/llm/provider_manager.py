"""
LLM Provider Manager with fallback logic
- Portions generated by AI
"""

from typing import Optional, Dict, List
import logging

from .base import BaseLLMProvider, LLMUnavailableError
from .gemini_provider import GeminiProvider
from .groq_provider import GroqProvider
from .openai_provider import OpenAIProvider

logger = logging.getLogger(__name__)

# Provider instances (singletons)
_providers: Dict[str, BaseLLMProvider] = {}

# Fallback order
FALLBACK_ORDER = ['gemini', 'groq', 'openai']


def _get_provider_instance(name: str) -> Optional[BaseLLMProvider]:
    """Get or create a provider instance."""
    if name not in _providers:
        if name == 'gemini':
            _providers[name] = GeminiProvider()
        elif name == 'groq':
            _providers[name] = GroqProvider()
        elif name == 'openai':
            _providers[name] = OpenAIProvider()
        else:
            return None
    return _providers[name]


def get_available_providers() -> List[Dict[str, any]]:
    """
    Get list of all providers with their availability status.
    
    Returns:
        List of dicts with provider name and availability
    """
    result = []
    for name in FALLBACK_ORDER:
        provider = _get_provider_instance(name)
        result.append({
            'name': name,
            'available': provider.is_available() if provider else False,
            'display_name': {
                'gemini': 'Google Gemini Flash',
                'groq': 'Groq (Llama 3.3)',
                'openai': 'OpenAI GPT-4o-mini'
            }.get(name, name)
        })
    return result


def get_active_provider(preferred_provider: str = 'gemini') -> Optional[BaseLLMProvider]:
    """
    Get the active LLM provider, falling back if needed.
    
    Args:
        preferred_provider: The user's preferred provider from settings
        
    Returns:
        An available provider, or None if none available
    """
    # Try preferred provider first
    provider = _get_provider_instance(preferred_provider)
    if provider and provider.is_available():
        return provider
    
    # Fallback to other providers in order
    for name in FALLBACK_ORDER:
        if name != preferred_provider:
            provider = _get_provider_instance(name)
            if provider and provider.is_available():
                logger.info(f"Using fallback LLM provider: {name}")
                return provider
    
    return None


def get_active_provider_or_raise(preferred_provider: str = 'gemini') -> BaseLLMProvider:
    """
    Get the active LLM provider or raise an error.
    
    Args:
        preferred_provider: The user's preferred provider from settings
        
    Returns:
        An available provider
        
    Raises:
        LLMUnavailableError: If no provider is available
    """
    provider = get_active_provider(preferred_provider)
    if provider is None:
        raise LLMUnavailableError(
            "No LLM provider configured. Please add at least one API key "
            "(GEMINI_API_KEY, GROQ_API_KEY, or OPENAI_API_KEY) in Admin settings."
        )
    return provider
