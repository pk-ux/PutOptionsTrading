"""
Groq LLM Provider for AI stock analysis
- Portions generated by AI

Free tier: 30 RPM, uses Llama 3.3 70B
"""

import time
from typing import Dict, Any
from groq import Groq

from .base import BaseLLMProvider, AnalysisError
from ...core.config import get_settings


class GroqProvider(BaseLLMProvider):
    """Groq provider for stock analysis using Llama models."""
    
    name = "groq"
    
    def __init__(self):
        self.settings = get_settings()
        self._client = None
        
        if self.is_available():
            self._client = Groq(api_key=self.settings.GROQ_API_KEY)
    
    def is_available(self) -> bool:
        """Check if Groq is configured."""
        return bool(self.settings.GROQ_API_KEY)
    
    async def generate_analysis(self, prompt: str) -> Dict[str, Any]:
        """Generate analysis using Groq."""
        if not self.is_available():
            raise AnalysisError("Groq API key not configured")
        
        try:
            start_time = time.time()
            
            response = self._client.chat.completions.create(
                model="llama-3.3-70b-versatile",
                messages=[
                    {"role": "system", "content": self.get_system_prompt()},
                    {"role": "user", "content": prompt}
                ],
                temperature=0.3,
                max_tokens=4096,
            )
            
            elapsed = time.time() - start_time
            print(f"[Groq] Response time: {elapsed:.2f}s")
            
            if not response.choices or not response.choices[0].message.content:
                raise AnalysisError("Empty response from Groq")
            
            return self.extract_json_from_response(response.choices[0].message.content)
            
        except AnalysisError:
            raise
        except Exception as e:
            if "API key" in str(e).lower() or "authentication" in str(e).lower():
                raise AnalysisError("Invalid Groq API key")
            raise AnalysisError(f"Groq analysis failed: {str(e)}")
