"""
Shared Greeks Calculator using Black-Scholes model
- Portions generated by AI

This module provides centralized Greeks calculations for all API clients.
Used by Alpaca, Massive, and Yahoo Finance clients as fallback when
API-provided Greeks are unavailable (e.g., when markets are closed).

The risk-free rate is automatically loaded from the admin-configurable
market settings stored in the database.
"""

import numpy as np
from scipy.stats import norm
from scipy.optimize import brentq
from typing import Optional, Dict


def _get_risk_free_rate() -> float:
    """
    Get the risk-free rate from market settings.
    Wrapped in a function to avoid circular imports.
    """
    try:
        from ..core.market_settings import get_risk_free_rate
        return get_risk_free_rate()
    except ImportError:
        # Fallback if settings not available
        return 0.0367  # Default: 3.67%


def calculate_d1(S: float, K: float, T: float, r: float, sigma: float) -> float:
    """
    Calculate d1 parameter for Black-Scholes model.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years (DTE / 365)
        r: Risk-free rate (as decimal, e.g., 0.0367 for 3.67%)
        sigma: Implied volatility (as decimal, e.g., 0.30 for 30%)
        
    Returns:
        d1 value for Black-Scholes formula
    """
    if T <= 0 or sigma <= 0:
        return 0.0
    return (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))


def calculate_d2(S: float, K: float, T: float, r: float, sigma: float) -> float:
    """
    Calculate d2 parameter for Black-Scholes model.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        r: Risk-free rate
        sigma: Implied volatility
        
    Returns:
        d2 value for Black-Scholes formula
    """
    if T <= 0 or sigma <= 0:
        return 0.0
    d1 = calculate_d1(S, K, T, r, sigma)
    return d1 - sigma * np.sqrt(T)


def calculate_delta_put(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None
) -> float:
    """
    Calculate put option delta using Black-Scholes.
    
    Delta measures the rate of change of option price with respect to 
    the underlying asset price. For puts, delta is always negative 
    (between -1 and 0).
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years (DTE / 365)
        sigma: Implied volatility (as decimal)
        r: Risk-free rate (optional - uses admin-configured value if not provided)
        
    Returns:
        Put delta (between -1 and 0)
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0 or sigma <= 0:
        # At or past expiry
        return -1.0 if S < K else 0.0
    
    d1 = calculate_d1(S, K, T, r, sigma)
    return -norm.cdf(-d1)


def calculate_delta_call(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None
) -> float:
    """
    Calculate call option delta using Black-Scholes.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        r: Risk-free rate (optional)
        
    Returns:
        Call delta (between 0 and 1)
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0 or sigma <= 0:
        return 1.0 if S > K else 0.0
    
    d1 = calculate_d1(S, K, T, r, sigma)
    return norm.cdf(d1)


def calculate_gamma(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None
) -> float:
    """
    Calculate option gamma using Black-Scholes.
    
    Gamma measures the rate of change of delta with respect to 
    the underlying asset price. Same for puts and calls.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        r: Risk-free rate (optional)
        
    Returns:
        Gamma value
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0 or sigma <= 0 or S <= 0:
        return 0.0
    
    d1 = calculate_d1(S, K, T, r, sigma)
    return norm.pdf(d1) / (S * sigma * np.sqrt(T))


def calculate_theta_put(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None,
    per_day: bool = True
) -> float:
    """
    Calculate put option theta using Black-Scholes.
    
    Theta measures the rate of change of option price with respect to time.
    Typically negative (option loses value as time passes).
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        r: Risk-free rate (optional)
        per_day: If True, returns daily theta; if False, returns annual theta
        
    Returns:
        Put theta (typically negative)
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0 or sigma <= 0:
        return 0.0
    
    d1 = calculate_d1(S, K, T, r, sigma)
    d2 = d1 - sigma * np.sqrt(T)
    
    term1 = -(S * norm.pdf(d1) * sigma) / (2 * np.sqrt(T))
    term2 = r * K * np.exp(-r * T) * norm.cdf(-d2)
    
    theta = term1 + term2
    
    if per_day:
        return theta / 365
    return theta


def calculate_theta_call(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None,
    per_day: bool = True
) -> float:
    """
    Calculate call option theta using Black-Scholes.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        r: Risk-free rate (optional)
        per_day: If True, returns daily theta; if False, returns annual theta
        
    Returns:
        Call theta (typically negative)
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0 or sigma <= 0:
        return 0.0
    
    d1 = calculate_d1(S, K, T, r, sigma)
    d2 = d1 - sigma * np.sqrt(T)
    
    term1 = -(S * norm.pdf(d1) * sigma) / (2 * np.sqrt(T))
    term2 = -r * K * np.exp(-r * T) * norm.cdf(d2)
    
    theta = term1 + term2
    
    if per_day:
        return theta / 365
    return theta


def calculate_vega(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None,
    per_percent: bool = True
) -> float:
    """
    Calculate option vega using Black-Scholes.
    
    Vega measures the rate of change of option price with respect to 
    implied volatility. Same for puts and calls.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        r: Risk-free rate (optional)
        per_percent: If True, returns vega per 1% change in IV
        
    Returns:
        Vega value
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0 or sigma <= 0:
        return 0.0
    
    d1 = calculate_d1(S, K, T, r, sigma)
    vega = S * norm.pdf(d1) * np.sqrt(T)
    
    if per_percent:
        return vega / 100  # Per 1% change in IV
    return vega


def calculate_rho_put(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None,
    per_percent: bool = True
) -> float:
    """
    Calculate put option rho using Black-Scholes.
    
    Rho measures the rate of change of option price with respect to 
    the risk-free interest rate.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        r: Risk-free rate (optional)
        per_percent: If True, returns rho per 1% change in rate
        
    Returns:
        Put rho (typically negative for puts)
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0 or sigma <= 0:
        return 0.0
    
    d2 = calculate_d2(S, K, T, r, sigma)
    rho = -K * T * np.exp(-r * T) * norm.cdf(-d2)
    
    if per_percent:
        return rho / 100
    return rho


def calculate_implied_volatility(
    option_price: float, 
    S: float, 
    K: float, 
    T: float, 
    option_type: str = 'put',
    r: Optional[float] = None,
    max_iterations: int = 100,
    tolerance: float = 1e-6
) -> float:
    """
    Calculate implied volatility by inverting Black-Scholes.
    
    Uses Brent's method for root finding to find the IV that produces
    the given option price.
    
    Args:
        option_price: Market price of the option
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        option_type: 'put' or 'call'
        r: Risk-free rate (optional)
        max_iterations: Maximum iterations for solver
        tolerance: Convergence tolerance
        
    Returns:
        Implied volatility (as decimal), or 0.0 if cannot be solved
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0 or option_price <= 0:
        return 0.0
    
    # Check intrinsic value
    if option_type == 'put':
        intrinsic = max(0, K * np.exp(-r * T) - S)
    else:
        intrinsic = max(0, S - K * np.exp(-r * T))
    
    if option_price < intrinsic:
        # Option price below intrinsic value - can't solve
        return 0.0
    
    def bs_price(sigma: float) -> float:
        """Black-Scholes price for given sigma."""
        if sigma <= 0:
            return 0.0
        d1 = calculate_d1(S, K, T, r, sigma)
        d2 = d1 - sigma * np.sqrt(T)
        
        if option_type == 'put':
            return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)
        else:
            return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    
    try:
        # Search for IV in range [0.001, 5.0] (0.1% to 500%)
        iv = brentq(
            lambda sigma: bs_price(sigma) - option_price, 
            0.001, 
            5.0,
            maxiter=max_iterations,
            xtol=tolerance
        )
        return iv
    except (ValueError, RuntimeError):
        # Cannot find IV in the given range
        return 0.0


def calculate_all_greeks(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    option_type: str = 'put',
    r: Optional[float] = None
) -> Dict[str, float]:
    """
    Calculate all Greeks at once for efficiency.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        option_type: 'put' or 'call'
        r: Risk-free rate (optional)
        
    Returns:
        Dictionary with delta, gamma, theta, vega, rho
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if option_type == 'put':
        return {
            'delta': calculate_delta_put(S, K, T, sigma, r),
            'gamma': calculate_gamma(S, K, T, sigma, r),
            'theta': calculate_theta_put(S, K, T, sigma, r),
            'vega': calculate_vega(S, K, T, sigma, r),
            'rho': calculate_rho_put(S, K, T, sigma, r),
        }
    else:
        return {
            'delta': calculate_delta_call(S, K, T, sigma, r),
            'gamma': calculate_gamma(S, K, T, sigma, r),
            'theta': calculate_theta_call(S, K, T, sigma, r),
            'vega': calculate_vega(S, K, T, sigma, r),
            'rho': calculate_rho_put(S, K, T, sigma, r) * -1,  # Call rho is opposite sign
        }


def calculate_put_price(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None
) -> float:
    """
    Calculate theoretical put option price using Black-Scholes.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        r: Risk-free rate (optional)
        
    Returns:
        Theoretical put price
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0:
        # At expiry, return intrinsic value
        return max(0, K - S)
    
    if sigma <= 0:
        # No volatility - return discounted intrinsic
        return max(0, K * np.exp(-r * T) - S)
    
    d1 = calculate_d1(S, K, T, r, sigma)
    d2 = d1 - sigma * np.sqrt(T)
    
    return K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)


def calculate_call_price(
    S: float, 
    K: float, 
    T: float, 
    sigma: float, 
    r: Optional[float] = None
) -> float:
    """
    Calculate theoretical call option price using Black-Scholes.
    
    Args:
        S: Current stock price
        K: Strike price
        T: Time to expiry in years
        sigma: Implied volatility
        r: Risk-free rate (optional)
        
    Returns:
        Theoretical call price
    """
    if r is None:
        r = _get_risk_free_rate()
    
    if T <= 0:
        # At expiry, return intrinsic value
        return max(0, S - K)
    
    if sigma <= 0:
        # No volatility - return discounted intrinsic
        return max(0, S - K * np.exp(-r * T))
    
    d1 = calculate_d1(S, K, T, r, sigma)
    d2 = d1 - sigma * np.sqrt(T)
    
    return S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
