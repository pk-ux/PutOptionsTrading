def calculate_metrics(options_chain: pd.DataFrame, current_price: float) -> pd.DataFrame:
    """Calculate additional metrics for options"""
    if options_chain.empty:
        return options_chain
    
    # Calculate if option is out of the money (strike price below current price for puts)
    options_chain['out_of_the_money'] = options_chain['strike'] < current_price
    
    # Get current date
    today = datetime.now().date()
    
    # Calculate days to expiration (DTE)
    options_chain['calendar_days'] = options_chain['expiry'].apply(
        lambda x: max((datetime.strptime(x, '%Y-%m-%d').date() - today).days + 1, 1)
    )
    
    # Calculate annualized return based on option premium using calendar time
    CALENDAR_DAYS_PER_YEAR = 365
    
    options_chain['annualized_return'] = (
        options_chain['lastPrice'] / options_chain['strike'] * (CALENDAR_DAYS_PER_YEAR / options_chain['calendar_days']) * 100
    )
    
    return options_chain


def screen_options(options_df: pd.DataFrame, config: dict, api_source: str = "massive") -> pd.DataFrame:
    """
    Apply screening criteria to filter options.
    
    For Alpaca API: Volume is fetched AFTER all other filters are applied
    to minimize API calls (only fetch volume for filtered contracts).
    
    Args:
        options_df: DataFrame with options data
        config: Configuration dictionary with screening criteria
        api_source: API source ("massive", "alpaca", or "yahoo")
        
    Returns:
        Filtered DataFrame with options meeting all criteria
    """
    if options_df.empty:
        return options_df
    
    criteria = config['screening_criteria']
    strategy = config['options_strategy']
    
    # Rename openInterest to open_interest if needed
    if 'openInterest' in options_df.columns and 'open_interest' not in options_df.columns:
        options_df['open_interest'] = options_df['openInterest']
    
    # Convert max assignment probability to delta threshold
    # e.g., 20% probability = delta >= -0.20 (delta between -0.20 and 0)
    max_prob = criteria.get('max_assignment_probability', 20) / 100
    
    # Step 1: Apply all NON-VOLUME filters first
    # This allows us to minimize API calls for volume data (Alpaca)
    non_volume_conditions = (
        (options_df['open_interest'] >= strategy['min_open_interest']) &
        (options_df['delta'] >= -max_prob) &
        (options_df['annualized_return'] >= criteria['min_annualized_return']) &
        (options_df['out_of_the_money'])
    )
    
    filtered = options_df[non_volume_conditions].copy()
    
    if filtered.empty:
        return filtered
    
    # Step 2: For Alpaca, fetch volume for filtered contracts only
    # This is the optimization - we only fetch volume for contracts that pass other filters
    is_alpaca = api_source.lower() == "alpaca"
    has_volume_data = filtered['volume'].max() > 0
    
    if is_alpaca and not has_volume_data and 'contract_symbol' in filtered.columns:
        print(f"  Fetching volume for {len(filtered)} filtered contracts from Alpaca...")
        contract_symbols = filtered['contract_symbol'].tolist()
        volumes = fetch_alpaca_volumes(contract_symbols)
        
        # Update volume column with fetched data
        filtered['volume'] = filtered['contract_symbol'].map(volumes).fillna(0).astype(int)
        has_volume_data = filtered['volume'].max() > 0
    
    # Step 3: Apply volume filter (now that we have volume data)
    min_volume = strategy.get('min_volume', 0)
    if has_volume_data and min_volume > 0:
        filtered = filtered[filtered['volume'] >= min_volume]
    elif not has_volume_data and min_volume > 0:
        # If still no volume data and min_volume is required, log warning
        print(f"  WARNING: Volume data not available, skipping volume filter (min_volume={min_volume})")
    
    if filtered.empty:
        return filtered
    
    # Sort results
    sort_by = config['output']['sort_by']
    filtered = filtered.sort_values(
        by=sort_by,
        ascending=[config['output']['sort_order'] == 'ascending'] * len(sort_by)
    )
    
    return filtered.head(config['output']['max_results'])


def format_output(filtered_df: pd.DataFrame, current_price: Optional[float] = None) -> pd.DataFrame:
    """Format the output DataFrame for display"""
    if filtered_df.empty:
        return filtered_df
    
    display_columns = [
        'symbol', 'current_price', 'strike', 'lastPrice', 'annualized_return', 'daily_decay_contract',
        'prob_assign', 'expiry', 'calendar_days', 'volume', 'open_interest', 'impliedVolatility'
    ]
    
    formatted = filtered_df.copy()
    
    if current_price is not None:
        formatted['current_price'] = current_price
    
    # Only keep columns that exist in the DataFrame
    display_columns = [col for col in display_columns if col in formatted.columns]
    formatted = formatted[display_columns]
    
    # Format implied volatility as percentage
    if 'impliedVolatility' in formatted.columns:
        formatted['impliedVolatility'] = formatted['impliedVolatility'] * 100
        formatted['impliedVolatility'] = formatted['impliedVolatility'].round(2)
    
    # Round other numerical columns
    if 'annualized_return' in formatted.columns:
        formatted['annualized_return'] = formatted['annualized_return'].round(2)
    
    # Calculate probability of assignment: abs(delta) * 100
    if 'delta' in filtered_df.columns:
        formatted['prob_assign'] = (filtered_df['delta'].abs() * 100).round(1)
    
    # Calculate daily decay: abs(theta)
    if 'theta' in filtered_df.columns:
        formatted['daily_decay_contract'] = filtered_df['theta'].abs().round(4)
    
    return formatted
