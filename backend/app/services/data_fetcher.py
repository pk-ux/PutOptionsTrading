"""
Data fetcher for stock analysis - Yahoo Finance and calculated technicals
- Portions generated by AI
"""

from typing import Dict, Any, Optional, List
from datetime import datetime, timedelta
import logging
import yfinance as yf
import numpy as np

logger = logging.getLogger(__name__)


def fetch_yahoo_data(symbol: str) -> Dict[str, Any]:
    """
    Fetch comprehensive stock data from Yahoo Finance.
    
    Args:
        symbol: Stock ticker symbol
        
    Returns:
        Dictionary with price data, fundamentals, and event dates
    """
    try:
        ticker = yf.Ticker(symbol)
        info = ticker.info
        
        # Get current price data
        current_price = info.get('currentPrice') or info.get('regularMarketPrice')
        previous_close = info.get('previousClose') or info.get('regularMarketPreviousClose')
        
        # Calculate change percentage
        change_percent = None
        if current_price and previous_close:
            change_percent = ((current_price - previous_close) / previous_close) * 100
        
        # Get earnings date
        earnings_date = None
        days_to_earnings = None
        try:
            calendar = ticker.calendar
            if calendar is not None and not calendar.empty:
                if 'Earnings Date' in calendar.index:
                    earnings_dates = calendar.loc['Earnings Date']
                    if isinstance(earnings_dates, (list, tuple)) and len(earnings_dates) > 0:
                        earnings_date = str(earnings_dates[0].date()) if hasattr(earnings_dates[0], 'date') else str(earnings_dates[0])
                    elif hasattr(earnings_dates, 'date'):
                        earnings_date = str(earnings_dates.date())
        except Exception as e:
            logger.debug(f"Could not fetch earnings date for {symbol}: {e}")
        
        # Calculate days to earnings
        if earnings_date:
            try:
                earnings_dt = datetime.strptime(earnings_date, '%Y-%m-%d')
                days_to_earnings = (earnings_dt - datetime.now()).days
            except:
                pass
        
        # Get ex-dividend date
        ex_dividend_date = None
        try:
            ex_div = info.get('exDividendDate')
            if ex_div:
                ex_dividend_date = datetime.fromtimestamp(ex_div).strftime('%Y-%m-%d')
        except:
            pass
        
        return {
            'current_price': current_price,
            'previous_close': previous_close,
            'change_percent': change_percent,
            'fifty_two_week_high': info.get('fiftyTwoWeekHigh'),
            'fifty_two_week_low': info.get('fiftyTwoWeekLow'),
            'volume': info.get('volume') or info.get('regularMarketVolume'),
            'avg_volume': info.get('averageVolume'),
            'market_cap': info.get('marketCap'),
            'pe_ratio': info.get('trailingPE'),
            'forward_pe': info.get('forwardPE'),
            'beta': info.get('beta'),
            'earnings_date': earnings_date,
            'days_to_earnings': days_to_earnings,
            'ex_dividend_date': ex_dividend_date,
            'dividend_yield': info.get('dividendYield'),
            'sector': info.get('sector'),
            'industry': info.get('industry'),
        }
        
    except Exception as e:
        logger.error(f"Error fetching Yahoo data for {symbol}: {e}")
        return {}


def fetch_price_history(symbol: str, days: int = 60) -> List[Dict[str, Any]]:
    """
    Fetch price history for technical analysis.
    
    Args:
        symbol: Stock ticker symbol
        days: Number of days of history
        
    Returns:
        List of OHLCV data points
    """
    try:
        ticker = yf.Ticker(symbol)
        hist = ticker.history(period=f"{days}d")
        
        if hist.empty:
            return []
        
        data = []
        for date, row in hist.iterrows():
            data.append({
                'date': date.strftime('%Y-%m-%d'),
                'open': float(row['Open']),
                'high': float(row['High']),
                'low': float(row['Low']),
                'close': float(row['Close']),
                'volume': int(row['Volume']),
            })
        
        return data
        
    except Exception as e:
        logger.error(f"Error fetching price history for {symbol}: {e}")
        return []


def calculate_technicals(price_history: List[Dict[str, Any]], current_price: float = None) -> Dict[str, Any]:
    """
    Calculate technical indicators from price history.
    
    Args:
        price_history: List of OHLCV data points
        current_price: Current stock price (optional, uses last close if not provided)
        
    Returns:
        Dictionary with technical indicators
    """
    if not price_history or len(price_history) < 14:
        return {}
    
    closes = np.array([p['close'] for p in price_history])
    highs = np.array([p['high'] for p in price_history])
    lows = np.array([p['low'] for p in price_history])
    
    price = current_price if current_price else closes[-1]
    
    result = {}
    
    # RSI (14-day)
    try:
        result['rsi_14'] = calculate_rsi(closes, 14)
    except:
        result['rsi_14'] = None
    
    # Simple Moving Averages
    if len(closes) >= 20:
        result['sma_20'] = float(np.mean(closes[-20:]))
    if len(closes) >= 50:
        result['sma_50'] = float(np.mean(closes[-50:]))
    if len(closes) >= 200:
        result['sma_200'] = float(np.mean(closes[-200:]))
    
    # Determine trend
    sma_20 = result.get('sma_20')
    sma_50 = result.get('sma_50')
    if sma_20 and sma_50:
        if price > sma_20 > sma_50:
            result['trend'] = 'UPTREND'
        elif price < sma_20 < sma_50:
            result['trend'] = 'DOWNTREND'
        else:
            result['trend'] = 'SIDEWAYS'
    
    # Support and Resistance (simple: recent lows and highs)
    recent_days = min(20, len(price_history))
    recent_lows = lows[-recent_days:]
    recent_highs = highs[-recent_days:]
    
    result['support_level'] = float(np.min(recent_lows))
    result['resistance_level'] = float(np.max(recent_highs))
    
    return result


def calculate_rsi(closes: np.ndarray, period: int = 14) -> float:
    """
    Calculate Relative Strength Index.
    
    Args:
        closes: Array of closing prices
        period: RSI period (default 14)
        
    Returns:
        RSI value
    """
    if len(closes) < period + 1:
        return None
    
    deltas = np.diff(closes)
    gains = np.where(deltas > 0, deltas, 0)
    losses = np.where(deltas < 0, -deltas, 0)
    
    # Use exponential moving average
    avg_gain = np.mean(gains[:period])
    avg_loss = np.mean(losses[:period])
    
    for i in range(period, len(gains)):
        avg_gain = (avg_gain * (period - 1) + gains[i]) / period
        avg_loss = (avg_loss * (period - 1) + losses[i]) / period
    
    if avg_loss == 0:
        return 100.0
    
    rs = avg_gain / avg_loss
    rsi = 100 - (100 / (1 + rs))
    
    return float(rsi)


def get_all_analysis_data(symbol: str) -> Dict[str, Any]:
    """
    Fetch all data needed for stock analysis.
    Combines Yahoo Finance data with calculated technicals.
    
    Args:
        symbol: Stock ticker symbol
        
    Returns:
        Complete data dictionary for analysis
    """
    # Fetch Yahoo data
    yahoo_data = fetch_yahoo_data(symbol)
    
    # Fetch price history and calculate technicals
    price_history = fetch_price_history(symbol, days=60)
    technicals = calculate_technicals(
        price_history, 
        current_price=yahoo_data.get('current_price')
    )
    
    return {
        'yahoo': yahoo_data,
        'technicals': technicals,
        'price_history': price_history,
    }
