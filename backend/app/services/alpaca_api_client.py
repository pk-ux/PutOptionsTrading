"""
Alpaca API Client - Real-time stock and options data provider
- Portions generated by AI

Data sources:
- Stock prices: Real-time last trade price (more accurate than mid-point)
- Options prices: Real-time with bid/ask quotes, Greeks, and IV
- Open Interest: From Trading API's get_option_contracts()
- News: Benzinga feed (historical back to 2015)

Requires Alpaca Algo Trader Plus subscription for real-time options data.
"""

import pandas as pd
import traceback
from datetime import datetime, timedelta, timezone
from typing import Dict, Any, Optional, List

from ..core.config import get_settings


class AlpacaAPIClient:
    """
    Alpaca API client wrapper for options screening.
    
    Data sources:
    - Stock prices: Real-time last trade price
    - Options prices: Real-time with bid/ask quotes (mid-point available)
    - Options Greeks: From Data API snapshots, or calculated via Black-Scholes if unavailable
    - Implied Volatility: From Data API, or calculated if unavailable
    - Open Interest: From Trading API's get_option_contracts()
    - Volume: From Data API snapshots
    - News: Benzinga feed via Alpaca
    
    Note: Requires Alpaca Algo Trader Plus subscription for real-time options data.
    """
    
    def __init__(self, use_midpoint_pricing: bool = True):
        settings = get_settings()
        self.api_key = settings.ALPACA_API_KEY
        self.secret_key = settings.ALPACA_SECRET_KEY
        self.use_midpoint_pricing = use_midpoint_pricing
        
        if not self.api_key or not self.secret_key:
            raise ValueError(
                "ALPACA_API_KEY and ALPACA_SECRET_KEY not found in environment variables. "
                "Please set them in your backend/.env file."
            )
        
        # Import and initialize the Alpaca clients
        try:
            from alpaca.data.historical import StockHistoricalDataClient, OptionHistoricalDataClient
            from alpaca.data.historical.news import NewsClient
            from alpaca.trading.client import TradingClient
            
            # Data API clients (for quotes, trades, bars)
            self.stock_client = StockHistoricalDataClient(
                api_key=self.api_key,
                secret_key=self.secret_key
            )
            self.option_client = OptionHistoricalDataClient(
                api_key=self.api_key,
                secret_key=self.secret_key
            )
            self.news_client = NewsClient(
                api_key=self.api_key,
                secret_key=self.secret_key
            )
            
            # Trading API client (for option contracts with OI)
            # Use paper=True to access contract data (works with most subscriptions)
            self.trade_client = TradingClient(
                api_key=self.api_key,
                secret_key=self.secret_key,
                paper=True
            )
            
            print("Alpaca API clients initialized (Data + Trading APIs)")
        except ImportError:
            raise ImportError(
                "alpaca-py library not installed. "
                "Please run: pip install alpaca-py>=0.43.0"
            )
    
    def _fetch_option_volumes(self, contract_symbols: List[str]) -> Dict[str, int]:
        """
        Fetch daily volume for specific option contracts.
        
        Strategy:
        1. First try get_option_bars with TimeFrame.Day (efficient batch request)
        2. If bars return 0 volume, fall back to get_option_trades and sum trade sizes
        
        This method is called AFTER filtering to minimize API calls - only fetching
        volume for contracts that pass all other screening criteria.
        
        Args:
            contract_symbols: List of contract symbols to fetch volume for
            
        Returns:
            Dictionary mapping contract symbol to daily volume
        """
        if not contract_symbols:
            return {}
        
        try:
            from alpaca.data.requests import OptionBarsRequest, OptionTradesRequest
            from alpaca.data.timeframe import TimeFrame
            
            print(f"  Fetching volume for {len(contract_symbols)} filtered contracts...")
            
            volumes = {}
            
            # Step 1: Try get_option_bars first (efficient batch request)
            # Use UTC timezone for consistency with Alpaca API responses
            now_utc = datetime.now(timezone.utc)
            request = OptionBarsRequest(
                symbol_or_symbols=contract_symbols,
                timeframe=TimeFrame.Day,
                start=now_utc - timedelta(days=1)
            )
            bars = self.option_client.get_option_bars(request)
            
            # Extract volume from the latest daily bar for each contract
            symbols_with_zero_volume = []
            for symbol in contract_symbols:
                if symbol in bars and bars[symbol]:
                    vol = int(bars[symbol][-1].volume)
                    volumes[symbol] = vol
                    if vol == 0:
                        symbols_with_zero_volume.append(symbol)
                else:
                    volumes[symbol] = 0
                    symbols_with_zero_volume.append(symbol)
            
            # Step 2: For symbols with 0 volume from bars, try get_option_trades
            # This sums up individual trade sizes to calculate daily volume
            if symbols_with_zero_volume:
                print(f"  Bars returned 0 volume for {len(symbols_with_zero_volume)} contracts, trying trades API...")
                
                try:
                    # Fetch trades for the last 7 days (API limit)
                    # Use 7 days to ensure we capture the last trading day even on weekends
                    # Use UTC timezone for consistency with Alpaca API responses
                    trades_request = OptionTradesRequest(
                        symbol_or_symbols=symbols_with_zero_volume,
                        start=now_utc - timedelta(days=7),
                        end=now_utc
                    )
                    trades = self.option_client.get_option_trades(trades_request)
                    
                    # Sum up trade sizes for each symbol
                    # Note: Access trades via .data attribute for TradeSet objects
                    trades_found = 0
                    trades_data = trades.data if hasattr(trades, 'data') else trades
                    
                    for symbol in symbols_with_zero_volume:
                        # Try both access methods
                        symbol_trades = None
                        if isinstance(trades_data, dict):
                            symbol_trades = trades_data.get(symbol)
                        elif symbol in trades:
                            symbol_trades = trades[symbol]
                        
                        if symbol_trades:
                            # Sum all trade sizes for this symbol
                            # Group by date and get the most recent trading day's volume
                            daily_volumes = {}
                            for trade in symbol_trades:
                                trade_date = trade.timestamp.strftime('%Y-%m-%d')
                                if trade_date not in daily_volumes:
                                    daily_volumes[trade_date] = 0
                                daily_volumes[trade_date] += int(trade.size)
                            
                            # Get the most recent day's volume
                            if daily_volumes:
                                latest_date = max(daily_volumes.keys())
                                latest_volume = daily_volumes[latest_date]
                                if latest_volume > 0:
                                    volumes[symbol] = latest_volume
                                    trades_found += 1
                    
                    if trades_found > 0:
                        # Log which date's volume we're using (helpful for debugging weekend/holiday data)
                        sample_dates = set()
                        for sym in symbols_with_zero_volume[:5]:  # Sample first 5
                            if sym in volumes and volumes[sym] > 0:
                                # Find the date for this symbol from trades_data
                                sym_trades = trades_data.get(sym) if isinstance(trades_data, dict) else None
                                if sym_trades:
                                    dates = set(t.timestamp.strftime('%Y-%m-%d') for t in sym_trades)
                                    sample_dates.update(dates)
                        if sample_dates:
                            latest_sample_date = max(sample_dates)
                            print(f"  Found volume via trades API for {trades_found} contracts (data from {latest_sample_date})")
                        
                except Exception as trades_err:
                    print(f"  WARNING: Could not fetch trades for volume: {str(trades_err)}")
            
            total_volume = sum(volumes.values())
            non_zero = sum(1 for v in volumes.values() if v > 0)
            print(f"  Volume data: {non_zero}/{len(contract_symbols)} contracts have volume, total: {total_volume}")
            
            return volumes
            
        except Exception as e:
            print(f"  WARNING: Could not fetch option volumes: {str(e)}")
            traceback.print_exc()
            # Return zeros for all contracts on error
            return {symbol: 0 for symbol in contract_symbols}
    
    def _fetch_option_contracts(
        self, 
        symbol: str, 
        min_exp_date: datetime, 
        max_exp_date: datetime
    ) -> Dict[str, Dict[str, Any]]:
        """
        Fetch option contracts from Trading API to get open interest.
        
        The Trading API's get_option_contracts() provides open interest data
        that is not available in the Data API's option chain endpoint.
        
        Uses pagination to fetch all contracts (API returns max 100 per page).
        
        Args:
            symbol: Underlying stock symbol
            min_exp_date: Minimum expiration date
            max_exp_date: Maximum expiration date
            
        Returns:
            Dictionary mapping contract symbol to contract data including open_interest
        """
        try:
            from alpaca.trading.requests import GetOptionContractsRequest
            from alpaca.trading.enums import ContractType, AssetStatus
            
            print(f"  Fetching option contracts for {symbol} from Trading API (for OI)...")
            
            # Build a lookup dictionary: contract_symbol -> contract data
            contracts_dict = {}
            page_token = None
            page_count = 0
            max_pages = 20  # Safety limit to prevent infinite loops
            
            while page_count < max_pages:
                page_count += 1
                
                # Build request with pagination
                # Note: limit can be up to 10000 per the API docs
                request = GetOptionContractsRequest(
                    underlying_symbols=[symbol],
                    type=ContractType.PUT,
                    status=AssetStatus.ACTIVE,
                    expiration_date_gte=min_exp_date.strftime('%Y-%m-%d'),
                    expiration_date_lte=max_exp_date.strftime('%Y-%m-%d'),
                    limit=10000,  # Max allowed by API
                    page_token=page_token,
                )
                
                contracts_response = self.trade_client.get_option_contracts(request)
                
                # Extract contracts from response
                if contracts_response and hasattr(contracts_response, 'option_contracts'):
                    contracts = contracts_response.option_contracts or []
                elif contracts_response:
                    contracts = contracts_response if isinstance(contracts_response, list) else []
                else:
                    contracts = []
                
                if not contracts:
                    break
                
                for contract in contracts:
                    contract_symbol = contract.symbol
                    
                    # Extract key data from contract
                    # Note: Some fields may be strings, convert as needed
                    oi = contract.open_interest
                    if oi:
                        oi = int(oi) if isinstance(oi, str) else int(oi)
                    else:
                        oi = 0
                        
                    close_px = contract.close_price
                    if close_px:
                        close_px = float(close_px) if isinstance(close_px, str) else float(close_px)
                    else:
                        close_px = 0.0
                        
                    contracts_dict[contract_symbol] = {
                        'open_interest': oi,
                        'close_price': close_px,
                        'strike_price': float(contract.strike_price) if contract.strike_price else None,
                        'expiration_date': contract.expiration_date.isoformat() if contract.expiration_date else None,
                        'size': int(contract.size) if contract.size else 100,  # Contract multiplier
                    }
                
                # Check for next page
                if hasattr(contracts_response, 'next_page_token') and contracts_response.next_page_token:
                    page_token = contracts_response.next_page_token
                else:
                    break  # No more pages
            
            print(f"  Found {len(contracts_dict)} PUT contracts with OI data (pages: {page_count})")
            return contracts_dict
            
        except Exception as e:
            print(f"  WARNING: Could not fetch option contracts from Trading API: {str(e)}")
            traceback.print_exc()
            return {}
    
    def get_stock_price(self, symbol: str) -> Optional[float]:
        """
        Get current stock price using last trade price (more accurate than mid-point).
        
        Falls back to mid-point of bid/ask if no recent trade available.
        
        Args:
            symbol: Stock ticker symbol (e.g., 'AAPL')
            
        Returns:
            Stock price as float, or None if unavailable
        """
        try:
            from alpaca.data.requests import StockLatestTradeRequest, StockLatestQuoteRequest
            
            print(f"Fetching price for {symbol} from Alpaca (last trade)...")
            
            # Try to get last trade price first (most accurate)
            try:
                trade_request = StockLatestTradeRequest(symbol_or_symbols=symbol)
                trades = self.stock_client.get_stock_latest_trade(trade_request)
                
                if symbol in trades:
                    trade = trades[symbol]
                    price = trade.price
                    if price and price > 0:
                        print(f"Alpaca last trade for {symbol}: ${price:.2f}")
                        return round(float(price), 2)
            except Exception as trade_err:
                print(f"Could not get last trade for {symbol}: {trade_err}")
            
            # Fallback to quotes if no recent trade
            print(f"Falling back to quote for {symbol}...")
            quote_request = StockLatestQuoteRequest(symbol_or_symbols=symbol)
            quotes = self.stock_client.get_stock_latest_quote(quote_request)
            
            if symbol in quotes:
                quote = quotes[symbol]
                bid = quote.bid_price
                ask = quote.ask_price
                
                if bid and ask and bid > 0 and ask > 0:
                    mid_price = (bid + ask) / 2
                    print(f"Alpaca mid-point for {symbol}: ${mid_price:.2f} (bid: ${bid:.2f}, ask: ${ask:.2f})")
                    return round(mid_price, 2)
                elif bid and bid > 0:
                    return round(bid, 2)
                elif ask and ask > 0:
                    return round(ask, 2)
            
            print(f"WARNING: Could not get Alpaca price for {symbol}")
            return None
                
        except Exception as e:
            print(f"ERROR getting Alpaca price for {symbol}: {str(e)}")
            return None
    
    def get_stock_quote(self, symbol: str) -> Dict[str, Any]:
        """
        Get stock quote in format compatible with existing code.
        
        Args:
            symbol: Stock ticker symbol
            
        Returns:
            Dictionary with success status and price data
        """
        price = self.get_stock_price(symbol)
        
        if price is not None:
            return {
                'success': True,
                'symbol': symbol,
                'mid_price': price,
                'last_price': price,
                'source': 'alpaca'
            }
        else:
            return {
                'success': False,
                'error': f'Could not get price for {symbol}'
            }
    
    def get_options_chain(self, symbol: str, config: Dict[str, Any]) -> pd.DataFrame:
        """
        Get options chain with prices and Greeks from Alpaca API.
        
        Data sources (merged):
        - Trading API: Option contracts with open interest, close prices
        - Data API: Real-time snapshots with bid/ask quotes, Greeks, IV
        
        Fallback strategy:
        - Greeks: Use API values, fall back to Black-Scholes calculation if None
        - IV: Use API value, fall back to Black-Scholes implied volatility if None
        - OI: Use Trading API value (Data API doesn't provide it)
        - Price: Mid-point > last trade > close_price (from Trading API)
        
        Args:
            symbol: Stock ticker symbol
            config: Configuration dictionary with options_strategy settings
            
        Returns:
            DataFrame with options data including prices and Greeks
        """
        try:
            from alpaca.data.requests import OptionChainRequest
            from alpaca.trading.enums import ContractType
            from .greeks_calculator import (
                calculate_all_greeks,
                calculate_implied_volatility
            )
            
            print(f"Fetching options chain for {symbol} from Alpaca...")
            
            # Extract DTE range from config
            max_dte = config['options_strategy']['max_dte']
            min_dte = config['options_strategy'].get('min_dte', 0)
            
            # Calculate date range for expiration filtering
            today = datetime.now().date()
            min_exp_date = today + timedelta(days=min_dte)
            max_exp_date = today + timedelta(days=max_dte)
            
            print(f"  Expiration range: {min_exp_date} to {max_exp_date} (DTE: {min_dte}-{max_dte})")
            
            # Step 1: Fetch option contracts from Trading API (for OI and close price)
            contracts_dict = self._fetch_option_contracts(symbol, min_exp_date, max_exp_date)
            
            # Step 2: Fetch real-time snapshots from Data API (for quotes and Greeks)
            request = OptionChainRequest(
                underlying_symbol=symbol,
                type=ContractType.PUT,
                expiration_date_gte=min_exp_date,
                expiration_date_lte=max_exp_date,
            )
            chain = self.option_client.get_option_chain(request)
            print(f"  Found {len(chain)} PUT option snapshots from Data API")
            
            # Get current stock price for Black-Scholes calculations
            stock_price = self.get_stock_price(symbol)
            if stock_price is None:
                print(f"  WARNING: Could not get stock price for {symbol}, Greeks calculation may fail")
            
            options_data = []
            stats = {
                'total': 0,
                'greeks_from_api': 0,
                'greeks_calculated': 0,
                'iv_from_api': 0,
                'iv_calculated': 0,
                'oi_from_trading_api': 0,
                'skipped_no_price': 0,
            }
            
            for contract_symbol, snapshot in chain.items():
                stats['total'] += 1
                
                # Parse contract symbol (format: SYMBOL YYMMDD P/C STRIKE)
                # e.g., AAPL250117P00230000 = AAPL Jan 17 2025 $230 Put
                try:
                    symbol_end = len(symbol)
                    date_str = contract_symbol[symbol_end:symbol_end + 6]
                    strike_str = contract_symbol[symbol_end + 7:]
                    
                    year = 2000 + int(date_str[0:2])
                    month = int(date_str[2:4])
                    day = int(date_str[4:6])
                    expiration = f"{year:04d}-{month:02d}-{day:02d}"
                    strike = int(strike_str) / 1000.0
                except Exception as parse_err:
                    print(f"  Could not parse contract symbol {contract_symbol}: {parse_err}")
                    continue
                
                # Calculate DTE
                try:
                    exp_date = datetime.strptime(expiration, '%Y-%m-%d').date()
                    dte = (exp_date - today).days
                except Exception:
                    continue
                
                # Time to expiry in years (for Black-Scholes)
                T = dte / 365.0
                
                # ---------- PRICE EXTRACTION ----------
                # Priority: mid-point > last trade > close_price (from Trading API)
                option_price = None
                price_source = None
                
                # Try latest quote for bid/ask
                if hasattr(snapshot, 'latest_quote') and snapshot.latest_quote:
                    quote = snapshot.latest_quote
                    bid = getattr(quote, 'bid_price', None)
                    ask = getattr(quote, 'ask_price', None)
                    
                    if self.use_midpoint_pricing and bid and ask and bid > 0 and ask > 0:
                        option_price = (bid + ask) / 2
                        price_source = 'mid_point'
                    elif bid and bid > 0:
                        option_price = bid
                        price_source = 'bid'
                    elif ask and ask > 0:
                        option_price = ask
                        price_source = 'ask'
                
                # Fallback to latest trade
                if option_price is None and hasattr(snapshot, 'latest_trade') and snapshot.latest_trade:
                    trade = snapshot.latest_trade
                    trade_price = getattr(trade, 'price', None)
                    if trade_price and trade_price > 0:
                        option_price = float(trade_price)
                        price_source = 'last_trade'
                
                # Fallback to close_price from Trading API contracts
                if option_price is None and contract_symbol in contracts_dict:
                    close_price = contracts_dict[contract_symbol].get('close_price', 0)
                    if close_price and close_price > 0:
                        option_price = float(close_price)
                        price_source = 'close_price'
                
                # Skip options without valid price
                if option_price is None or option_price <= 0:
                    stats['skipped_no_price'] += 1
                    continue
                
                # ---------- OPEN INTEREST (from Trading API) ----------
                open_interest = 0
                if contract_symbol in contracts_dict:
                    open_interest = contracts_dict[contract_symbol].get('open_interest', 0) or 0
                    if open_interest > 0:
                        stats['oi_from_trading_api'] += 1
                
                # ---------- IMPLIED VOLATILITY ----------
                iv = getattr(snapshot, 'implied_volatility', None)
                if iv is not None:
                    iv = float(iv)
                    stats['iv_from_api'] += 1
                elif stock_price and T > 0:
                    # Calculate IV using Black-Scholes inverse
                    iv = calculate_implied_volatility(
                        option_price=option_price,
                        S=stock_price,
                        K=strike,
                        T=T,
                        option_type='put'
                    )
                    if iv > 0:
                        stats['iv_calculated'] += 1
                    else:
                        iv = 0.3  # Default IV if calculation fails
                else:
                    iv = 0.3  # Default IV
                
                # ---------- GREEKS ----------
                # Try to get from API first
                greeks_data = None
                if hasattr(snapshot, 'greeks') and snapshot.greeks:
                    api_greeks = snapshot.greeks
                    delta = float(api_greeks.delta) if api_greeks.delta is not None else None
                    
                    if delta is not None:
                        greeks_data = {
                            'delta': delta,
                            'gamma': float(api_greeks.gamma) if api_greeks.gamma is not None else 0,
                            'theta': float(api_greeks.theta) if api_greeks.theta is not None else 0,
                            'vega': float(api_greeks.vega) if api_greeks.vega is not None else 0,
                            'rho': float(api_greeks.rho) if api_greeks.rho is not None else 0,
                        }
                        stats['greeks_from_api'] += 1
                
                # Fallback: Calculate Greeks using Black-Scholes
                if greeks_data is None and stock_price and T > 0 and iv > 0:
                    greeks_data = calculate_all_greeks(
                        S=stock_price,
                        K=strike,
                        T=T,
                        sigma=iv,
                        option_type='put'
                    )
                    stats['greeks_calculated'] += 1
                
                # Skip if we couldn't get Greeks
                if greeks_data is None:
                    continue
                
                # ---------- BUILD OPTION ROW ----------
                option_row = {
                    'symbol': symbol,
                    'strike': float(strike),
                    'expiry': expiration,
                    'dte': dte,
                    'volume': 0,  # Data API doesn't provide reliable volume; fetched later
                    'open_interest': int(open_interest),
                    'lastPrice': float(option_price),
                    'price_source': price_source,
                    'impliedVolatility': iv,
                    'delta': greeks_data['delta'],
                    'gamma': greeks_data['gamma'],
                    'theta': greeks_data['theta'],
                    'vega': greeks_data['vega'],
                    'rho': greeks_data['rho'],
                    'contract_symbol': contract_symbol
                }
                
                options_data.append(option_row)
            
            if not options_data:
                print(f"No valid options data found for {symbol}")
                return pd.DataFrame()
            
            df = pd.DataFrame(options_data)
            
            # Print statistics
            print(f"  Retrieved {len(df)} PUT options for {symbol}")
            print(f"  Stats: Greeks (API: {stats['greeks_from_api']}, Calc: {stats['greeks_calculated']}), "
                  f"IV (API: {stats['iv_from_api']}, Calc: {stats['iv_calculated']}), "
                  f"OI from Trading API: {stats['oi_from_trading_api']}, "
                  f"Skipped (no price): {stats['skipped_no_price']}")
            
            return df
                
        except Exception as e:
            print(f"ERROR getting Alpaca options chain for {symbol}: {str(e)}")
            traceback.print_exc()
            return pd.DataFrame()
    
    def get_ticker_news(self, symbol: str, limit: int = 10, max_age_days: int = 7) -> List[Dict[str, Any]]:
        """
        Fetch news for a ticker using Alpaca NewsClient.
        
        Args:
            symbol: Stock ticker symbol (e.g., 'AAPL')
            limit: Number of news items to fetch (default: 10)
            max_age_days: Only include news from last N days (default: 7)
            
        Returns:
            List of news items with title, url, published date, and source
        """
        try:
            from alpaca.data.requests import NewsRequest
            
            print(f"Fetching news for {symbol} from Alpaca (Benzinga)...")
            
            end = datetime.now(timezone.utc)
            start = end - timedelta(days=max_age_days)
            
            request = NewsRequest(
                symbols=symbol,
                start=start,
                end=end,
                limit=limit
            )
            
            news_response = self.news_client.get_news(request)
            
            news_items = []
            # Access news list from response.data['news']
            articles = news_response.data.get('news', []) if hasattr(news_response, 'data') else []
            for article in articles:
                # Format date for display
                published_date = article.created_at
                date_display = ""
                published_str = ""
                
                if published_date:
                    date_display = published_date.strftime("%b %d")
                    published_str = published_date.isoformat()
                
                news_items.append({
                    'title': article.headline,
                    'url': article.url,
                    'published': published_str,
                    'date_display': date_display,
                    'source': article.source or 'Benzinga'
                })
            
            print(f"  Retrieved {len(news_items)} news items for {symbol}")
            return news_items
            
        except Exception as e:
            print(f"Error fetching Alpaca news for {symbol}: {str(e)}")
            return []


# Global instance for easy import
alpaca_client: Optional[AlpacaAPIClient] = None


def get_alpaca_client(use_midpoint_pricing: bool = True) -> Optional[AlpacaAPIClient]:
    """
    Get or create the Alpaca API client singleton.
    
    If the client exists but use_midpoint_pricing differs from the current setting,
    the client is recreated to reflect the new setting.
    """
    global alpaca_client
    
    # Check if we need to recreate the client due to midpoint setting change
    if alpaca_client is not None and alpaca_client.use_midpoint_pricing != use_midpoint_pricing:
        print(f"[Alpaca] Midpoint pricing changed from {alpaca_client.use_midpoint_pricing} to {use_midpoint_pricing}, recreating client")
        alpaca_client = None
    
    if alpaca_client is None:
        try:
            alpaca_client = AlpacaAPIClient(use_midpoint_pricing=use_midpoint_pricing)
        except Exception as e:
            print(f"Failed to initialize Alpaca API client: {str(e)}")
            alpaca_client = None
    return alpaca_client


def reset_alpaca_client():
    """Reset the Alpaca client singleton (useful when settings change)."""
    global alpaca_client
    alpaca_client = None
