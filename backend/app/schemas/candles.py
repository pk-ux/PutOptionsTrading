"""
Candle chart Pydantic schemas
- Portions generated by AI
"""

from typing import Dict, List
from pydantic import BaseModel


class CandleBar(BaseModel):
    """One daily OHLCV bar (time as YYYY-MM-DD)"""
    time: str
    open: float
    high: float
    low: float
    close: float
    volume: int


class OverlayPoint(BaseModel):
    """One point of an indicator overlay line"""
    time: str
    value: float


class CandlesResponse(BaseModel):
    """Daily candles plus SMA/EMA overlay series for the price chart"""
    symbol: str
    as_of: str
    candles: List[CandleBar]
    overlays: Dict[str, List[OverlayPoint]]
